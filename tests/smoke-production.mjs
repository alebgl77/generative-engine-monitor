/**
 * Production-server smoke, mock provider only; no process is spawned here.
 * Start a production server and worker against the SAME isolated migrated DB.
 * Seed the mock provider before starting the worker (its limits load at startup).
 * Run with SMOKE_ALLOW_MUTATION=1, SMOKE_BASE_URL=http://127.0.0.1:3000,
 * and an explicit loopback DATABASE_URL. Never point this at a real user DB.
 */
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { setTimeout as delay } from "node:timers/promises";
import bcrypt from "bcryptjs";
import { PrismaClient } from "@prisma/client";

const loopback = new Set(["localhost", "127.0.0.1", "[::1]", "::1"]);
assert.equal(process.env.SMOKE_ALLOW_MUTATION, "1", "Set SMOKE_ALLOW_MUTATION=1 only for an isolated disposable test database");
assert.ok(process.env.SMOKE_BASE_URL, "SMOKE_BASE_URL must be explicit");
assert.ok(process.env.DATABASE_URL, "DATABASE_URL must be explicit");
const base = new URL(process.env.SMOKE_BASE_URL);
const database = new URL(process.env.DATABASE_URL);
assert.ok(loopback.has(base.hostname) && loopback.has(database.hostname), "Smoke only accepts loopback HTTP and PostgreSQL hosts");
assert.ok(["http:", "https:"].includes(base.protocol), "Invalid HTTP scheme");
assert.ok(["postgres:", "postgresql:"].includes(database.protocol), "Invalid PostgreSQL scheme");
assert.equal(base.username + base.password, "", "HTTP URL must not carry credentials");
const db = new PrismaClient();
const fixture = `smoke-${randomUUID()}`;
const email = `${fixture}@integration.test`;
const password = `${randomUUID()}-OnlyATest9!`;
const cookies = new Map();
let userId;
let createdProviderId;
let step = "health";

async function request(path, options = {}, authenticated = true) {
  const url = new URL(path, base);
  assert.equal(url.origin, base.origin, "Smoke requests cannot leave the configured origin");
  const headers = new Headers(options.headers);
  if (authenticated && cookies.size) headers.set("cookie", [...cookies].map(([name, value]) => `${name}=${value}`).join("; "));
  const response = await fetch(url, { ...options, headers, redirect: "manual", signal: AbortSignal.timeout(20000) });
  if (authenticated) for (const cookie of response.headers.getSetCookie()) {
    const first = cookie.split(";", 1)[0];
    const separator = first.indexOf("=");
    if (separator > 0) cookies.set(first.slice(0, separator), first.slice(separator + 1));
  }
  return response;
}

async function json(path, { method = "GET", body, status = 200 } = {}) {
  const response = await request(path, { method, ...(body === undefined ? {} : {
    headers: { "content-type": "application/json" }, body: JSON.stringify(body),
  }) });
  assert.ok((Array.isArray(status) ? status : [status]).includes(response.status), `${step}: ${method} ${path} returned HTTP ${response.status}`);
  const text = await response.text();
  assert.ok(!/\b(?:NaN|Infinity)\b/.test(text), `${step}: invalid numeric response`);
  return JSON.parse(text);
}

async function cleanup() {
  if (userId) {
    await db.$transaction(async (tx) => {
      // Audit rows generated by this test only; normal production audit retention
      // is untouched by the app's project/user cascades.
      const projects = await tx.project.findMany({ where: { userId }, select: { id: true } });
      await tx.auditLog.deleteMany({ where: { OR: [{ userId }, { projectId: { in: projects.map((project) => project.id) } }] } });
      await tx.user.deleteMany({ where: { id: userId, email } });
      await tx.rateLimitBucket.deleteMany({ where: { key: { in: [`runs:${userId}`, `rescores:${userId}`, `login:email:${email}`] } } });
    });
  }
  if (createdProviderId) await db.$transaction(async (tx) => {
    await tx.$queryRaw`SELECT id FROM providers WHERE id = ${createdProviderId} FOR UPDATE`;
    const tasks = await tx.runTask.count({ where: { providerId: createdProviderId } });
    const credentials = await tx.providerCredential.count({ where: { providerId: createdProviderId } });
    if (!tasks && !credentials) await tx.provider.deleteMany({ where: { id: createdProviderId, code: "mock" } });
  });
}

try {
  for (const path of ["/login", "/api/health/live", "/api/health/ready"]) {
    assert.equal((await request(path, {}, false)).status, 200, `${path} must be reachable in the production build`);
  }
  assert.equal((await request("/api/projects", {}, false)).status, 401, "Protected API must reject an anonymous request");

  step = "fixture";
  let provider = await db.provider.findUnique({ where: { code: "mock" } });
  if (!provider) {
    provider = await db.provider.create({ data: {
      code: "mock", label: "Mock smoke", isActiveGlobal: true,
      supportsParametric: true, supportsGrounded: true, defaultModel: "mock-fixture",
    } });
    createdProviderId = provider.id;
    console.log("Mock provider created: start/restart the external worker now so it discovers this provider.");
  }
  assert.ok(provider.isActiveGlobal && provider.supportsParametric && provider.supportsGrounded, "Existing mock provider must support both modes; this script does not alter existing providers");
  userId = (await db.user.create({ data: { email, name: fixture, passwordHash: await bcrypt.hash(password, 12) } })).id;
  assert.equal(await db.providerCredential.count({ where: { userId } }), 0, "Smoke fixture must never carry paid credentials");

  step = "authentication";
  const csrf = await json("/api/auth/csrf");
  assert.ok(csrf.csrfToken, "NextAuth CSRF token is missing");
  const login = await request("/api/auth/callback/credentials", {
    method: "POST", headers: { "content-type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ email, password, csrfToken: csrf.csrfToken, callbackUrl: new URL("/", base).href, json: "true" }),
  });
  assert.ok([200, 302].includes(login.status), "Credentials callback failed");
  assert.equal((await json("/api/auth/session")).user?.email, email, "A real authenticated NextAuth session is required");

  step = "planning";
  const project = await json("/api/projects", { method: "POST", status: 201, body: {
    name: fixture, repetitions: 2, samplingModes: ["PARAMETRIC", "GROUNDED"], targetCountry: "FR", targetLanguage: "fr",
  } });
  const prefix = `/api/projects/${project.id}`;
  const originalText = "meilleur CRM pour une petite entreprise";
  const query = await json(`${prefix}/queries`, { method: "POST", status: 201, body: { text: originalText } });
  const brand = await json(`${prefix}/brands`, { method: "POST", status: 201, body: { name: "HubSpot", domain: "hubspot.com", aliases: ["Hub Spot"] } });
  const plan = await json(`${prefix}/runs`, { method: "POST", status: 202 });
  assert.equal(plan.totalSamples, 4, "One query × two modes × two repeats should plan four mock calls");
  const storedRun = await db.run.findUniqueOrThrow({ where: { id: plan.runId }, include: { tasks: { include: { provider: true, samples: true } } } });
  assert.equal(storedRun.configSnapshot.reconstructed, false);
  assert.ok(storedRun.configSnapshot.entities.some((entity) => entity.id === brand.id && entity.name === "HubSpot"));
  assert.ok(storedRun.tasks.every((task) => task.provider.code === "mock" && task.queryTextSnapshot === originalText));
  assert.ok(storedRun.tasks.flatMap((task) => task.samples).every((sample) => /^[a-f0-9]{64}$/.test(sample.promptHash ?? "")));

  // Archive the catalog while workers may still be executing. Historical tasks
  // and scoring must continue using the immutable plan-time configuration.
  for (const path of [`${prefix}/queries/${query.id}`, `${prefix}/brands/${brand.id}`]) {
    const response = await request(path, { method: "DELETE" });
    assert.ok([200, 204].includes(response.status), "Catalog archival failed");
  }
  assert.equal((await json(`${prefix}/queries`)).length, 0);
  assert.equal((await json(`${prefix}/brands`)).length, 0);

  step = "worker completion";
  const deadline = Date.now() + 120000;
  let run;
  do {
    run = await db.run.findUniqueOrThrow({ where: { id: plan.runId } });
    if (["COMPLETED", "FAILED", "PARTIAL", "CANCELLED"].includes(run.status)) break;
    await delay(500);
  } while (Date.now() < deadline);
  assert.equal(run.status, "COMPLETED", "Mock run did not complete; check external worker and its startup provider list");
  assert.equal(run.doneSamples, 4);
  assert.equal(await db.sampleScore.count({ where: { runId: run.id, scoringVersion: run.scoringVersion } }), 4);
  assert.equal(await db.runScore.count({ where: { runId: run.id, scoringVersion: run.scoringVersion } }), 2);
  assert.equal(await db.aIResponse.count({ where: { sample: { runId: run.id } } }), 4);
  assert.equal(run.scoringVersion, "v3", "This smoke verifies the original v3 → replay v2 → explicit v3 promotion cycle");
  const originalScores = await db.sampleScore.findMany({
    where: { runId: run.id, scoringVersion: "v3" }, orderBy: { sampleId: "asc" },
  });
  const originalResponses = await db.aIResponse.findMany({
    where: { sample: { runId: run.id } }, orderBy: { sampleId: "asc" },
  });
  const originalAttempts = await db.runSample.findMany({
    where: { runId: run.id }, select: { id: true, attempt: true, model: true, tokensIn: true, tokensOut: true, promptHash: true },
    orderBy: { id: "asc" },
  });

  step = "historical readers";
  const detail = await json(`${prefix}/runs/${run.id}`);
  assert.equal(detail.status, "COMPLETED");
  assert.ok(detail.tasks.every((task) => task.query.text === originalText), "Archival must not erase historical query text");
  const overview = await json(`${prefix}/dashboard/overview`);
  assert.equal(overview.latestRun?.id, run.id);
  for (const axis of [overview.parametric, overview.grounded]) {
    assert.ok(axis && axis.n === 1 && axis.lowN, "Repeated calls are one independent query");
    assert.equal(axis.ciLow, null, "A single query cannot identify a confidence interval");
    assert.equal(axis.ciHigh, null);
  }
  await json(`${prefix}/dashboard/queries`);
  await json(`${prefix}/dashboard/sources`);
  const exported = await json(`${prefix}/export?format=json`);
  assert.equal(exported.rows.length, 2);
  assert.ok(exported.rows.every((row) => row.query === originalText && row.ciLow === null && row.ciHigh === null));
  const csv = await request(`${prefix}/export?format=csv`);
  assert.equal(csv.status, 200);
  assert.match(csv.headers.get("content-type") ?? "", /text\/csv/);
  assert.ok(!/\b(?:NaN|Infinity)\b/.test(await csv.text()), "CSV cannot contain invalid numeric output");

  for (const version of ["v2", "v3"]) {
    step = `rescore and promote ${version}`;
    const requested = await json(`${prefix}/rescore`, {
      method: "POST", status: [200, 202], body: { runId: run.id, scoringVersion: version },
    });
    assert.equal(requested.scoringVersion, version, "Replay response must identify the requested target");
    const promotionDeadline = Date.now() + 120000;
    let ready = false;
    do {
      const [currentProject, jobs] = await Promise.all([
        db.project.findUniqueOrThrow({ where: { id: project.id }, select: { activeScoringVersion: true } }),
        db.job.findMany({ where: { runId: run.id }, select: { kind: true, status: true, providerCode: true } }),
      ]);
      assert.ok(jobs.every((job) => job.providerCode === "mock" || job.providerCode === "internal"), "Replay must never create a real-provider job");
      assert.ok(!jobs.some((job) => ["FAILED", "DEAD", "CANCELLED"].includes(job.status)), `${version} replay ended with a failed or cancelled job`);
      ready = currentProject.activeScoringVersion === version && jobs.every((job) => job.status === "SUCCEEDED");
      if (ready) break;
      await delay(500);
    } while (Date.now() < promotionDeadline);
    assert.ok(ready, `${version} was not promoted after all replay and aggregate jobs completed`);

    const targetScores = await db.sampleScore.findMany({ where: { runId: run.id, scoringVersion: version } });
    assert.equal(targetScores.length, 4, "Promoted target must cover all four successful samples");
    const extractionVersions = [...new Set(targetScores.map((score) => score.extractionVersion))];
    assert.equal(extractionVersions.length, 1, "A target cannot mix extraction versions");
    const replayOverview = await json(`${prefix}/dashboard/overview`);
    assert.equal(replayOverview.scoringVersion, version);
    assert.equal(replayOverview.latestRun?.id, run.id);
    for (const axis of [replayOverview.parametric, replayOverview.grounded]) {
      assert.ok(axis && axis.n === 1 && axis.lowN, "A rescore must retain the independent-query population");
      assert.equal(axis.ciLow, null);
      assert.equal(axis.ciHigh, null);
    }
    const replayDetail = await json(`${prefix}/runs/${run.id}`);
    assert.equal(replayDetail.scoringVersion, version);
    assert.ok(replayDetail.tasks.every((task) => task.query.text === originalText), "Archived catalog must remain readable after replay");
    const replaySamples = replayDetail.tasksDetail.flatMap((task) => task.samples);
    assert.equal(replaySamples.length, 4);
    assert.ok(replaySamples.every((sample) => sample.status === "COMPLETED" && typeof sample.score === "number" && sample.text), "Replay must expose all four scored stored responses");
    const replayQueries = await json(`${prefix}/dashboard/queries`);
    assert.equal(replayQueries.scoringVersion, version);
    const replaySources = await json(`${prefix}/dashboard/sources`);
    assert.equal(replaySources.scoringVersion, version);
    assert.equal(replaySources.extractionVersion, extractionVersions[0], "Sources must use the promoted target's extraction version");
    const replayExport = await json(`${prefix}/export?format=json`);
    assert.equal(replayExport.scoringVersion, version);
    assert.equal(replayExport.rows.length, 2);
    assert.ok(replayExport.rows.every((row) => row.query === originalText && row.ciLow === null && row.ciHigh === null));

    assert.deepEqual(await db.aIResponse.findMany({ where: { sample: { runId: run.id } }, orderBy: { sampleId: "asc" } }), originalResponses, "Replay cannot replace or add any paid raw response");
    assert.deepEqual(await db.sampleScore.findMany({ where: { runId: run.id, scoringVersion: "v3" }, orderBy: { sampleId: "asc" } }), originalScores, "The four original v3 scores must remain byte-for-byte equivalent, including computation timestamps");
    assert.deepEqual(await db.runSample.findMany({
      where: { runId: run.id }, select: { id: true, attempt: true, model: true, tokensIn: true, tokensOut: true, promptHash: true }, orderBy: { id: "asc" },
    }), originalAttempts, "Replay cannot issue new provider attempts or rewrite provider usage");
    assert.equal(await db.job.count({ where: { runId: run.id, kind: "RUN_SAMPLE" } }), 4);
    assert.equal(await db.providerCredential.count({ where: { userId } }), 0, "Fixture must still have no paid-provider credentials");
    assert.equal((await db.run.findUniqueOrThrow({ where: { id: run.id } })).scoringVersion, "v3", "Promotion must not rewrite the run's original scoring version");
    assert.equal((await json(`${prefix}/queries`)).length, 0);
    assert.equal((await json(`${prefix}/brands`)).length, 0);
  }
  console.log("PASS production smoke: public health, anonymous 401, real session, immutable mock run, archived catalog, nullable intervals, dashboard/exports and v3 → v2 → v3 promotion with unchanged raw responses and original scores");
} catch (error) {
  console.error(`FAIL production smoke at ${step}: ${error instanceof assert.AssertionError ? error.message : error?.name ?? "Error"}`);
  process.exitCode = 1;
} finally {
  try { await cleanup(); }
  catch (error) { console.error(`Fixture cleanup failed (${error?.name ?? "Error"}); fixture id ${fixture}`); process.exitCode = 1; }
  await db.$disconnect();
}
